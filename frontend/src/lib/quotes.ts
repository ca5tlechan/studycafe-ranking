/** 오늘(로컬 날짜) 기준으로 하나 고른다 — 하루 동안 고정, 날짜가 바뀌면 다음 것. */
export function todaysQuote(now: Date = new Date()): Quote {
  const dayIndex = now.getFullYear() * 372 + now.getMonth() * 31 + now.getDate();
  return QUOTES[dayIndex % QUOTES.length];
}
